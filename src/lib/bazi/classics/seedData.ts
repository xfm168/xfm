// ============================================================

function buildStats(chapters: ClassicChapter[]): { totalChapters: number; totalParagraphs: number; totalSentences: number } {
  let totalParagraphs = 0
  let totalSentences = 0
  for (const ch of chapters) {
    totalParagraphs += ch.paragraphs.length
    for (const p of ch.paragraphs) {
      totalSentences += p.sentences.length
    }
  }
  return { totalChapters: chapters.length, totalParagraphs, totalSentences }
}

