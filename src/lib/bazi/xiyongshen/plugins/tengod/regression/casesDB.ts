import type { TenGodName, CombinationId, Wuxing } from '../types'

export interface TenGodCase {
  caseId: string
  name: string
  sourceClassic?: string
  difficulty?: '入门' | '进阶' | '高阶'
  fourPillars: {
    year: { gan: string; zhi: string }
    month: { gan: string; zhi: string }
    day: { gan: string; zhi: string }
    hour?: { gan: string; zhi: string }
  }
  dayGanWuxing: Wuxing
  monthZhiWuxing: Wuxing
  input: {
    dayGan: string
    dayGanWuxing: Wuxing
    monthZhi: Wuxing
    fourPillars: Array<{ gan: string; zhi: string; ganWx: Wuxing; zhiWx: Wuxing }>
    dayStrength?: number
    dayRootCount?: number
    isWinterBorn?: boolean
    isSummerBorn?: boolean
  }
  expected: {
    dominantTenGods: TenGodName[]
    weakTenGods?: TenGodName[]
    keyCombinations: Array<{ id: CombinationId | string; name: string; satisfiedExpected: boolean; favorable?: boolean }>
    balanceHint?: '中和' | '偏旺' | '极旺' | '偏弱' | '极弱'
  }
  tags: Array<'十神旺衰' | '十神组合' | '十神制化' | '十神流通'>
  notes?: string
}

const ganWxMap: Record<string, Wuxing> = {
  甲: '木', 乙: '木', 丙: '火', 丁: '火', 戊: '土',
  己: '土', 庚: '金', 辛: '金', 壬: '水', 癸: '水'
}
const zhiWxMap: Record<string, Wuxing> = {
  子: '水', 丑: '土', 寅: '木', 卯: '木', 辰: '土', 巳: '火',
  午: '火', 未: '土', 申: '金', 酉: '金', 戌: '土', 亥: '水'
}

const WINTER_ZHI = ['子', '丑', '亥']
const SUMMER_ZHI = ['巳', '午', '未']

function pillar(gan: string, zhi: string) {
  return { gan, zhi, ganWx: ganWxMap[gan], zhiWx: zhiWxMap[zhi] }
}

type RawCase = [
  string, string, string | undefined, '入门' | '进阶' | '高阶',
  string, string, string, string, string, string, string | undefined, string | undefined,
  TenGodName[], TenGodName[] | undefined,
  Array<{ id: CombinationId | string; name: string; satisfiedExpected: boolean; favorable?: boolean }>,
  '中和' | '偏旺' | '极旺' | '偏弱' | '极弱' | undefined,
  Array<'十神旺衰' | '十神组合' | '十神制化' | '十神流通'>,
  string?
]

function buildCase(raw: RawCase): TenGodCase {
  const [id, name, source, diff, yG, yZ, mG, mZ, dG, dZ, hG, hZ, dominant, weak, combos, balance, tags, notes] = raw
  const pillars = [pillar(yG, yZ), pillar(mG, mZ), pillar(dG, dZ)]
  if (hG && hZ) pillars.push(pillar(hG, hZ))
  return {
    caseId: id,
    name,
    sourceClassic: source,
    difficulty: diff,
    fourPillars: {
      year: { gan: yG, zhi: yZ },
      month: { gan: mG, zhi: mZ },
      day: { gan: dG, zhi: dZ },
      ...(hG && hZ ? { hour: { gan: hG, zhi: hZ } } : {})
    },
    dayGanWuxing: ganWxMap[dG],
    monthZhiWuxing: zhiWxMap[mZ],
    input: {
      dayGan: dG,
      dayGanWuxing: ganWxMap[dG],
      monthZhi: zhiWxMap[mZ],
      fourPillars: pillars,
      dayStrength: 50,
      dayRootCount: 1,
      isWinterBorn: WINTER_ZHI.includes(mZ),
      isSummerBorn: SUMMER_ZHI.includes(mZ)
    },
    expected: {
      dominantTenGods: dominant,
      weakTenGods: weak,
      keyCombinations: combos,
      balanceHint: balance
    },
    tags,
    notes
  }
}

