export class GejuKnowledgeBase {
  private entries = new Map<GejuName, GejuKnowledgeEntry>()

  constructor() {
    for (const e of ENTRIES) {
      this.entries.set(e.name, e)
    }
  }

  get(name: GejuName): GejuKnowledgeEntry | undefined {
    return this.entries.get(name)
  }

  has(name: GejuName): boolean {
    return this.entries.has(name)
  }

  listByCategory(cat: GejuCategory): GejuKnowledgeEntry[] {
    const list: GejuKnowledgeEntry[] = []
    for (const e of this.entries.values()) {
      if (e.category === cat) list.push(e)
    }
    list.sort((a, b) => a.priorityRank - b.priorityRank)
    return list
  }

  getAll(): GejuKnowledgeEntry[] {
    const list = Array.from(this.entries.values())
    list.sort((a, b) => a.priorityRank - b.priorityRank)
    return list
  }

  getCitations(name: GejuName): ClassicCitationFull[] {
    return this.entries.get(name)?.classicCitations || []
  }

  getChengGeConditions(name: GejuName): string[] {
    return this.entries.get(name)?.chengGeConditions || []
  }

  getPoGeConditions(name: GejuName): string[] {
    return this.entries.get(name)?.poGeConditions || []
  }
}

export const defaultGejuKnowledgeBase = new GejuKnowledgeBase()
