export interface ClassicCitationFull {
  classicCode: 'DTS' | 'QTB' | 'ZYQ' | 'ZPZQ' | 'YSX' | 'SMTH' | 'SBTK' | 'QLMG' | 'YDZP'
  classicName: string
  chapter: string
  section?: string
  originalText: string
  interpretation: string
  citationId?: string
}

export interface GejuKnowledgeEntry {
  name: GejuName
  category: GejuCategory
  priorityRank: number
  chengGeConditions: string[]
  chengGeRequiredCount: number
  poGeConditions: string[]
  jiaGeConditions: string[]
  zhenGeConditions: string[]
  zhuanGeConditions: string[]
  yongShenRules: string[]
  jiShenRules: string[]
  classicCitations: ClassicCitationFull[]
  remarks?: string
}

const CLASSIC_NAMES: Record<ClassicCitationFull['classicCode'], string> = {
  DTS: '滴天髓',
  QTB: '穷通宝鉴',
  ZYQ: '子平真诠',
  ZPZQ: '子平真诠',
  YSX: '渊海子平',
  SMTH: '三命通会',
  SBTK: '神峰通考',
  QLMG: '千里命稿',
  YDZP: '御定子平',
}

function makeCitation(
  code: ClassicCitationFull['classicCode'],
  chapter: string,
  originalText: string,
  interpretation: string,
  section?: string,
  citationId?: string,
): ClassicCitationFull {
  return {
    classicCode: code,
    classicName: CLASSIC_NAMES[code],
    chapter,
    section,
    originalText,
    interpretation,
    citationId,
  }
}

